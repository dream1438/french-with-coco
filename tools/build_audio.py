"""Tap-to-hear audio with the course voices (same Microsoft neural voices as the videos).

1. python tools/build_audio.py jobs      -> writes audio_jobs.json (one clip per French word, dialogue line, listening question)
2. On the PC: python pipeline/pipeline/edge_jobs.py audio_jobs.json web_audio   (needs edge-tts + internet)
3. Copy the mp3 files into french/audio/ and run: python tools/build_audio.py map   -> french/data/audio.js
Clips are named by a hash of (voice, rate, text), so re-running only adds new lines.
"""
import hashlib, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# voice + rate per speaker, from pipeline/config/voices.yaml (edge voices, speed multipliers)
VOICES = {
    "word": ("fr-FR-DeniseNeural", "-15%"),
    "Léa": ("fr-CH-ArianeNeural", "-12%"),
    "Madame Dubois": ("fr-FR-DeniseNeural", "-15%"),
    "Théo": ("fr-FR-RemyMultilingualNeural", "-12%"),
    "Karim": ("fr-FR-HenriNeural", "-18%"),
    "Le serveur": ("fr-FR-HenriNeural", "-18%"),
    "Le vendeur": ("fr-FR-HenriNeural", "-18%"),
    "Une passante": ("fr-FR-DeniseNeural", "-15%"),
}


def lessons():
    src = (ROOT / "french/data/lessons.js").read_text(encoding="utf-8")
    return json.loads(re.search(r"window\.COURSE_LESSONS\s*=\s*(\[.*\]);?\s*$", src, re.S).group(1))


def clean(t):
    return t.replace("·", ",").strip()


def items():
    seen = {}
    for l in lessons():
        for g in l["vocab"]:
            for i in g["items"]:
                seen.setdefault(i["fr"], VOICES["word"])
        for q in l.get("quiz") or []:
            if q.get("say"):
                seen.setdefault(q["say"], VOICES["word"])
        if l.get("dialogue"):
            for x in l["dialogue"]["lines"]:
                seen.setdefault(x["fr"], VOICES.get(x["who"], VOICES["word"]))
    for text, (voice, rate) in seen.items():
        name = hashlib.sha1(json.dumps([voice, rate, clean(text)], ensure_ascii=False).encode()).hexdigest()[:12]
        yield text, voice, rate, name


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "jobs"
    if cmd == "jobs":
        jobs = [{"file": n, "text": clean(t), "voice": v, "rate": r} for t, v, r, n in items()]
        out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "audio_jobs.json"
        out.write_text(json.dumps(jobs, ensure_ascii=False, indent=0), encoding="utf-8")
        print(len(jobs), "jobs ->", out)
    else:
        have = {p.stem for p in (ROOT / "french/audio").glob("*.mp3")}
        m = {t: n for t, v, r, n in items() if n in have}
        (ROOT / "french/data/audio.js").write_text(
            "// Generated by tools/build_audio.py: French text -> french/audio/<file>.mp3 (course voices)\n"
            "window.COURSE_AUDIO = " + json.dumps(m, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
        print(len(m), "of", len(list(items())), "lines have audio")
