// Builds supabase/seed.sql (course structure + lessons) from french/data/lessons.js and links.js.
// Usage: node tools/build_seed.js   (re-run after lessons or links change; upserts, safe to re-run)
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = { window: {} }; vm.createContext(ctx);
for (const f of ["french/data/lessons.js", "french/data/links.js"]) vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx);
const L = ctx.window.COURSE_LESSONS, K = ctx.window.COURSE_LINKS;
const q = (v) => v == null || v === "" ? "null" : "'" + String(v).replace(/'/g, "''") + "'";
const j = (v) => "'" + JSON.stringify(v).replace(/'/g, "''") + "'::jsonb";
const out = ["-- Generated by tools/build_seed.js. Do not edit by hand.", "begin;",
  "insert into public.languages (id,name,name_ar,sort) values ('fr','French','الفرنسية',1) on conflict (id) do update set name=excluded.name, name_ar=excluded.name_ar;"];
const levels = new Set(), units = new Map();
for (const l of L) {
  const lv = l.code.split("-")[0]; levels.add(lv);
  const m = /^(\S+)\s+(.*)$/.exec(l.unit) || [null, l.unit, l.unit];
  const uid = `fr-${lv}-${m[1]}`;
  if (!units.has(uid)) units.set(uid, { lv, code: m[1], title: m[2], sort: units.size + 1 });
  l._unit = uid;
}
[...levels].forEach((lv, i) => out.push(`insert into public.levels (id,language_id,code,title,sort) values (${q("fr-" + lv)},'fr',${q(lv)},${q(lv === "A1" ? "Beginner" : lv)},${i + 1}) on conflict (id) do update set title=excluded.title, sort=excluded.sort;`));
for (const [id, u] of units) out.push(`insert into public.units (id,level_id,code,title,sort) values (${q(id)},${q("fr-" + u.lv)},${q(u.code)},${q(u.title)},${u.sort}) on conflict (id) do update set title=excluded.title, sort=excluded.sort;`);
for (const l of L) {
  const lk = (K.lessons || {})[l.code] || {};
  const content = {}; for (const k of ["objectives", "grammar", "hook", "hookAr", "vocab", "quiz", "dialogue", "explain", "recap"]) if (l[k] !== undefined) content[k] = l[k];
  out.push(`insert into public.lessons (id,language_id,unit_id,code,n,slug,title,title_en,title_ar,length,video_en,video_ar,worksheet,content) values (` +
    [q("fr-" + l.code), "'fr'", q(l._unit), q(l.code), l.n, q(l.id), q(l.titleFr), q(l.titleEn), q(l.titleAr), q(l.length), q(lk.video), q(lk.videoAr), q(lk.worksheet), j(content)].join(",") +
    `) on conflict (id) do update set unit_id=excluded.unit_id, n=excluded.n, slug=excluded.slug, title=excluded.title, title_en=excluded.title_en, title_ar=excluded.title_ar, length=excluded.length, video_en=excluded.video_en, video_ar=coalesce(excluded.video_ar, public.lessons.video_ar), worksheet=excluded.worksheet, content=excluded.content, updated_at=now();`);
}
out.push("commit;");
fs.writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${levels.size} level(s), ${units.size} units, ${L.length} lessons`);
